require "rails_helper"

RSpec.describe "Icons", type: :request do
  let(:page) { Nokogiri::HTML(response.body) }
  let(:tokens) { Rails.root.join("app/assets/stylesheets/tokens/_colors.scss").read }

  def token(name)
    tokens[/\$#{name}:\s*(#\h{6})/, 1].downcase
  end

  def png_size(file_name)
    Rails.public_path.join(file_name).binread(24)[16, 8].unpack("N2")
  end

  describe "the head of the home page" do
    before { get root_path }

    it "declares the vector icon" do
      expect(page.at_css("link[rel='icon'][href='/icon.svg'][type='image/svg+xml']")).not_to be_nil
    end

    it "declares the classic favicon" do
      expect(page.at_css("link[rel='icon'][href='/favicon.ico']")).not_to be_nil
    end

    it "declares the iOS home screen icon" do
      expect(page.at_css("link[rel='apple-touch-icon'][href='/apple-touch-icon.png']")).not_to be_nil
    end

    it "only declares icons that can be fetched" do
      page.css("link[rel='icon'], link[rel='apple-touch-icon']").each do |link|
        get link["href"]
        expect(response).to have_http_status(:ok), "#{link['href']} answered #{response.status}"
      end
    end
  end

  it "serves /favicon.ico, which browsers request even without a declaration" do
    get "/favicon.ico"
    expect(response).to have_http_status(:ok)
  end

  describe "public/icon.svg" do
    let(:svg) { Rails.public_path.join("icon.svg").read.downcase }

    it "uses the brand magenta" do
      expect(svg).to include(token("na-dark-magenta"))
    end

    it "uses the dark theme background" do
      expect(svg).to include(token("na-dark-bg"))
    end

    it "is not the red circle generated by Rails" do
      expect(svg).not_to include('fill="red"')
    end
  end

  it "ships a 180 by 180 apple-touch-icon.png" do
    expect(png_size("apple-touch-icon.png")).to eq([ 180, 180 ])
  end

  it "ships a 512 by 512 icon.png" do
    expect(png_size("icon.png")).to eq([ 512, 512 ])
  end
end
